-- 1. Perfil público asociado a cada cuenta de Supabase Auth.
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default 'Swiftie'
    check (char_length(display_name) between 1 and 40),
  created_at timestamptz not null default now()
);

-- Crea o sincroniza el perfil de forma segura al registrarse una cuenta.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    coalesce(nullif(left(trim(new.raw_user_meta_data ->> 'display_name'), 40), ''), 'Swiftie')
  )
  on conflict (id) do update
    set display_name = excluded.display_name;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert or update on auth.users
  for each row execute function public.handle_new_user();

-- 2. Publicaciones de texto del feed comunitario.
create table if not exists public.community_posts (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.profiles (id) on delete cascade,
  title text not null check (char_length(title) between 1 and 100),
  content text not null check (char_length(content) between 1 and 2000),
  created_at timestamptz not null default now()
);

-- 3. Reseñas de álbumes y validación de puntuación.
create table if not exists public.album_reviews (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.profiles (id) on delete cascade,
  album_key text not null check (album_key in (
    'taylor-swift', 'fearless', 'speak-now', 'red', '1989', 'reputation',
    'lover', 'folklore', 'evermore', 'midnights', 'tortured-poets', 'showgirl'
  )),
  rating smallint not null check (rating between 1 and 5),
  content text not null check (char_length(content) between 10 and 1500),
  created_at timestamptz not null default now()
);

-- 4. Votos: una persona puede dar un me gusta por era.
create table if not exists public.era_likes (
  era_key text not null check (era_key in (
    'taylor-swift', 'fearless', 'speak-now', 'red', '1989', 'reputation',
    'lover', 'folklore', 'evermore', 'midnights', 'tortured-poets', 'showgirl'
  )),
  user_id uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (era_key, user_id)
);

-- 5. Metadatos de obras subidas; los archivos viven en Supabase Storage.
create table if not exists public.fan_art_posts (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.profiles (id) on delete cascade,
  title text not null check (char_length(title) between 1 and 100),
  description text not null default '' check (char_length(description) <= 1000),
  media_path text not null unique,
  media_type text not null check (media_type in (
    'image/jpeg', 'image/png', 'image/webp', 'image/gif', 'video/mp4', 'video/webm'
  )),
  created_at timestamptz not null default now()
);

