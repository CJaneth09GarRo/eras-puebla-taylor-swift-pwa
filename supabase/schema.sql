-- Expone solo conteos agregados de likes, no los identificadores de las cuentas.
create or replace function public.get_era_like_counts()
returns table (era_key text, like_count bigint)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select likes.era_key, count(*)::bigint
  from public.era_likes as likes
  group by likes.era_key;
$$;
revoke all on function public.get_era_like_counts() from public;
grant execute on function public.get_era_like_counts() to anon, authenticated;

-- 7. Bucket público de lectura con escritura limitada a la carpeta del usuario.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'fan-art',
  'fan-art',
  true,
  26214400,
  array['image/jpeg', 'image/png', 'image/webp', 'image/gif', 'video/mp4', 'video/webm']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Users upload fan art into their own folder" on storage.objects;
create policy "Users upload fan art into their own folder"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'fan-art'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists "Users delete fan art from their own folder" on storage.objects;
create policy "Users delete fan art from their own folder"
  on storage.objects for delete
  to authenticated
  using (
    bucket_id = 'fan-art'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

